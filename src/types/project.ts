export const projectCategories = [
  "Cloud & DevOps",
  "Backend & Web",
  "AI & Security",
  "GIS & IoT",
] as const;
export type ProjectCategory = (typeof projectCategories)[number];

export type ProjectMedia = {
  src: string;
  width: number;
  height: number;
  alt: string;
  caption: string;
  type:
    "screenshot" | "mobile" | "diagram" | "photo" | "presentation" | "workflow";
  provenance?: "original" | "competition-provided" | "reconstructed";
};

export type Project = {
  mobileShowcase?: MobileShowcase;
  slug: string;
  title: string;
  subtitle?: string;
  year: number;
  timeline?: string;
  category: ProjectCategory;
  tags: string[];
  type: string;
  role: string;
  featured: boolean;
  featuredOrder?: number;
  shortDescription: string;
  cardSummary?: string;
  overview: string[];
  challenge?: string;
  personalContributions?: string[];
  contributionStatement?: string;
  engineeringHighlights?: string[];
  impact?: string[];
  achievements?: string[];
  technologies: string[];
  architecture?: { description: string; media: ProjectMedia };
  status?: string;
  limitations?: string[];
  coverImage?: ProjectMedia;
  gallery?: ProjectMedia[];
  repositoryUrl?: string;
  liveUrl?: string;
  previousProject?: string;
  nextProject?: string;
};

export type ShowcaseScreen = {
  id: string;
  label: string;
  media?: ProjectMedia;
};

export type ShowcaseSlide = {
  id: string;
  layout: "hero" | "feature" | "comparison" | "scroll";
  eyebrow: string;
  title: string;
  description: string;
  screenIds: string[];
  annotations?: string[];
  /** Screen IDs for the unframed continuation and the smaller, flat device. */
  detailScreenId?: string;
  secondaryScreenId?: string;
  /** Photo overlay for this slide; falls back to the showcase composition. */
  backgroundPhoto?: string;
  headline?: { text: string; emphasis?: boolean }[][];
  /** Transparent device render, generated by capture-showcase.mjs. */
  poster?: string;
};

export type MobileShowcase = {
  logo?: ProjectMedia;
  composition?: {
    background: ProjectMedia;
    wordmark?: string;
    logoCrop?: { x: number; y: number; width: number; height: number };
    photoOpacity: number;
    whiteOverlay: number;
    newspaperOpacity: number;
    band: { top: number; height: number; newspaperStart: number; from: string; to: string };
  };
  theme: {
    primary: string;
    secondary: string;
    surface: string;
    ink: string;
    onPrimary: string;
    illustration?: string;
    backgroundPhoto?: string;
    backgroundCredit?: string;
    accent?: string;
    overlayOpacity: number;
  };
  screens: ShowcaseScreen[];
  hero: ShowcaseSlide & { layout: "hero" };
  slides: (ShowcaseSlide & { layout: "feature" | "comparison" | "scroll" })[];
};
